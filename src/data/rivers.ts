// Major Czech rivers as simplified courses (lon, lat), source → mouth.
// Anchored on real towns and confluences; meant to read as a river network at
// map scale, not as a navigable survey. Order matters: it is the flow.
export type River = {
  id: string;
  name: string;
  /** course points, mouth last */
  path: readonly (readonly [number, number])[];
  /** id of the river this one flows into; absent = leaves the country.
   *  The renderer snaps the last point onto the parent's course, so a
   *  tributary can never float a few hundred metres off its trunk. */
  joins?: string;
  /** relative size: trunk rivers are wider than their tributaries */
  order: number;
};

